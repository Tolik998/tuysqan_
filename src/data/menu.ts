function normalizedMenuImageUrl(imageUrl?: string) {
  if (!imageUrl?.startsWith("/menu-assets/")) return imageUrl;

  const fileName = imageUrl
    .split("/")
    .at(-1)
    ?.replace(/\.png$/i, ".webp");
  return fileName ? `/menu-normalized/${fileName}` : imageUrl;
}

